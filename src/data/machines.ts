import IMAGES from "./images.json";

const images: Record<string, { image: string; credit: string }> = IMAGES;

interface Opts {
  line?: string;
  uni?: boolean;
  years?: [number, number?];
  price?: 1 | 2 | 3 | 4;
  r?: Partial<Ratings>;
  s?: Partial<Specs>;
  url?: string;
}

export function slugify(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function def(
  brand: string,
  name: string,
  movement: Movement,
  load: LoadType,
  primary: Muscle[],
  secondary: Muscle[],
  curve: CurveShape,
  peak: number,
  description: string,
  o: Opts = {},
): Machine {
  const b = getBrand(brand);
  const id = slugify(`${brand} ${name}`);
  return {
    id,
    brand,
    name,
    line: o.line,
    movement,
    load,
    primary,
    secondary,
    curve,
    peak,
    unilateral: o.uni ?? false,
    years: o.years,
    description,
    ratings: deriveRatings(id, movement, load, b.build, o.r),
    specs: deriveSpecs(id, movement, load, o.s),
    priceTier: o.price ?? (load === "plate-loaded" ? 3 : 2),
    sourceUrl: o.url ?? b.url,
    image: images[id]?.image,
    imageCredit: images[id]?.credit,
  };
}

